def test_inventory_service_exceptions(test_db, tmp_path):
    """Tests that InventoryService methods raise appropriate ValidationErrors for edge cases."""
    inv_svc = InventoryService(test_db)
    
    # Non-existent file bulk import
    with pytest.raises(ValidationError, match="CSV file not found"):
        inv_svc.bulk_csv_import("non_existent_file.csv")
        
    # Non-existent product operations
    with pytest.raises(ValidationError, match="does not exist"):
        inv_svc.deactivate_product(999)
        
    with pytest.raises(ValidationError, match="does not exist"):
        inv_svc.update_product(Product(id=999, sku="SKU", name="Name"))
        
    with pytest.raises(ValidationError, match="does not exist"):
        inv_svc.record_delivery(sku="NONEXISTENT", quantity=10)
        
    with pytest.raises(ValidationError, match="does not exist"):
        inv_svc.submit_weekly_stock(sku="NONEXISTENT", remaining_stock=5, entry_date="2026-07-11")
        
    # Bulk import duplicate product name
    inv_svc.add_product(Product(sku="SKU-REAL", name="Real Product"))
    
    csv_file = tmp_path / "dup_name.csv"
    data = {
        "sku": ["SKU-NEW"],
        "name": ["Real Product"],  # Matches existing name but has different SKU
        "category": ["Fruit"],
        "current_stock": [10],
        "unit_cost": [2.5]
    }
    pd.DataFrame(data).to_csv(csv_file, index=False)
    
    with pytest.raises(DuplicateProductError):
        inv_svc.bulk_csv_import(str(csv_file))
